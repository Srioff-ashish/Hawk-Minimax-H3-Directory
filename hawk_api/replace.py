"""Person replacement: one person in a video swapped for a character whose face this server generated.

The video is cut into pieces on H3's 17k+5 frame grid, each no longer than the server's segment cap. Each piece is one
H3 render in MiniMax's documented "video editing" task -- the piece is <Video 1>, the character's pictures are
<Picture 1..n> -- so the motion, camera, timing and everyone else come from the piece and only the one person changes.
The finished pieces are joined and the original soundtrack is laid back untouched, so speech and music keep their
exact timing.

Who can be put INTO a video is limited on purpose: every picture of the character, and everything that picture was made
from, must have been generated by this server's own image engines. An uploaded photo, a picture from a URL or Drive,
one relabelled as generated, or anything edited from one of those is refused -- that would be putting a real person
into footage they were never in. The source video itself can be anything.
"""
