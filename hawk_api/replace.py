log = logging.getLogger(__name__)

FPS = 24
MAX_SECONDS = 90.0
MAX_PICTURES = 4
#: Stills from each piece shown to the vision model that writes that piece's prompt.
FRAMES_SHOWN = 6
POLL_SECONDS = 5.0
RENDER_WAIT_SECONDS = 6 * 3600
ASPECTS = {"16:9": 16 / 9, "9:16": 9 / 16, "1:1": 1.0, "4:3": 4 / 3, "3:4": 3 / 4, "21:9": 21 / 9, "9:21": 9 / 21}

SYSTEM_PROMPT = """You write one MiniMax H3 prompt for a VIDEO EDITING job: one person in a source video is replaced by a
character, and nothing else in the video changes.

You get: the user's direction (who is replaced, anything else they want), the character's name and description, the
character's identity pictures (<Picture 1>, <Picture 2> ...), and stills from the source video piece, in playback order,
which together are <Video 1>. The stills are frames of ONE video, not separate pictures.

Write exactly these six sections, each name alone on its line ending in a colon, content on the next line, one blank
line between sections, plain text, no markdown, nothing before or after:

subject_definitions:
<Subject 1> is the character: name the face, hair, skin tone and build visible in the identity pictures and cite them
("whose face, hair and build come from <Picture 1> and <Picture 2>"). Then one line per other person or element of the
video that needs tracking (<Subject 2> ...), described as they appear in <Video 1>.

summary:
Starts with "[video editing] The target video is an edited version of <Video 1>." then one short paragraph: which person
is replaced by <Subject 1>, and that everything else in <Video 1> is kept.

retention_analysis:
One line per label defined above, same order, each starting with that label: "<Subject 1>: fully_preserved - identity
from <Picture 1>: face, hair, skin tone, build." and for the video's other content "fully_preserved". Add
"<Video 1>: fully_preserved - motion, timing, camera, framing, background and every other person; only the replaced
person's identity is not kept." Markers allowed: fully_preserved, partially_preserved, attribute_transfer,
weak_reference.

detailed_description:
One line of style matching the video (photoreal, its grade and grain), then [Shot 1]. The longest section. <Subject 1>
takes the replaced person's exact place, body, pose, gestures, expressions, lip movement and timing frame for frame,
wearing the replaced person's clothing unless the direction says otherwise. Hands, contact, shadows and occlusion
match the new body. Camera, framing, depth of field, motion blur and lighting stay exactly as in <Video 1>. The face
from <Picture 1> holds steady with no drift. Keep [Shot 1] as the only shot unless the stills show a cut.

overall_soundscape:
Same as <Video 1>.

non_diegetic_music:
N/A

Rules: tags are exactly <Picture N>, <Video 1>, <Subject N> with a space before the number. Use only picture numbers
you were given. Describe only what the stills and the direction support; invent no new action or place. Every person
is an adult."""


# ------------------------------------------------------------------ pure helpers


def grid_up(frames: int) -> int:
    return 5 if frames <= 5 else 5 + 17 * math.ceil((frames - 5) / 17)


def grid_down(frames: int) -> int:
    return 0 if frames < 5 else 5 + 17 * ((frames - 5) // 17)


def piece_frames() -> int:
    """The longest piece: the server's segment cap, on the frame grid (12 s -> 277 frames, 15 s -> 345)."""
    return grid_down(int(max_segment_seconds() * FPS))


def cut_pieces(total: int, longest: int | None = None) -> list[dict]:
    """Where each piece starts and how many frames it has, all on H3's 17k+5 grid.

    ``skip`` is how many frames at the start of a piece were already covered by the one before it: the last piece is
    extended backwards onto the grid rather than losing the end of the video, and those frames are dropped on joining.
    A video shorter than one grid step above its length loses its last few frames (at most 16, 0.7 s) instead.
    """
    longest = longest or piece_frames()
    if total < 5:
        raise RequestError("The video is too short: H3 needs at least 5 frames.")
    out, start = [], 0
    while start < total:
        left = total - start
        if left >= longest:
            out.append({"start": start, "frames": longest, "skip": 0})
            start += longest
            continue
        need = grid_up(left)
        if need == left:
            out.append({"start": start, "frames": left, "skip": 0})
        elif out:
            out.append({"start": start - (need - left), "frames": need, "skip": need - left})
        else:
            out.append({"start": start, "frames": grid_down(left), "skip": 0})
        break
    return out


def nearest_aspect(width: int, height: int) -> str:
    ratio = width / height if height else 16 / 9
    return min(ASPECTS, key=lambda name: abs(math.log(ASPECTS[name] / ratio)))


def origin_problem(store, asset_id: str, _seen: set | None = None) -> str:
    """Why this picture cannot be put into a video ("" when it can): it, and everything it was made from, must come from
    this server's own image engines. Walks the whole chain, deleted ancestors included."""
    seen = _seen if _seen is not None else set()
    if asset_id in seen:
        return ""
    seen.add(asset_id)
    asset = store.lineage(asset_id)
    if asset is None:
        return f"{asset_id} has no record of where it came from"
    name = asset.get("filename") or asset_id
    source = asset.get("source") or {}
    kind = source.get("type") or "upload"
    if kind != "generated":
        return f"{name} is {'an uploaded file' if kind == 'upload' else f'imported from {kind}'}"
    if source.get("corrected_from") or source.get("restored_from") or not source.get("engine") \
            or source.get("engine") == "external":
        return f"{name} was not made by this server's image engines"
    for parent in source.get("references") or []:
        problem = origin_problem(store, str(parent), seen)
        if problem:
            return f"{name} was made from {problem}" if not problem.startswith(name) else problem
    return ""


def template_prompt(who: str, name: str, description: str, pictures: int, direction: str) -> str:
    """The prompt used when no vision model answers: the same six sections, from the request alone."""
    cited = " and ".join(f"<Picture {n}>" for n in range(1, pictures + 1))
    person = f"{name}, " if name else ""
    extra = f" {direction.strip()}" if direction.strip() else ""
    return (
        "subject_definitions:\n"
        f"<Subject 1> is {person}{description.strip() or 'the character'}, whose face, hair, skin tone and build come "
        f"from {cited}.\n\n"
        "summary:\n"
        "[video editing] The target video is an edited version of <Video 1>. "
        f"{who} in <Video 1> is replaced by <Subject 1>; everything else in <Video 1> is kept as it is.\n\n"
        "retention_analysis:\n"
        f"<Subject 1>: fully_preserved - identity from {cited}: face, hair, skin tone and build.\n"
        "<Video 1>: fully_preserved - motion, timing, camera, framing, background, lighting and every other person; "
        "only the replaced person's identity is not kept.\n\n"
        "detailed_description:\n"
        "Photoreal, matching the grade, grain and lighting of <Video 1>.\n"
        f"[Shot 1] <Subject 1> takes the exact place of {who} in <Video 1>: the same body position, pose, gestures, "
        "expressions, lip movement and timing, frame for frame, wearing the same clothing. Hands, contact shadows and "
        "occlusion match the new body. The camera, framing, depth of field, motion blur and light stay exactly as in "
        f"<Video 1>. The face from <Picture 1> holds steady with no drift.{extra}\n\n"
        "overall_soundscape:\nSame as <Video 1>.\n\n"
        "non_diegetic_music:\nN/A"
    )


def usable_prompt(text: str) -> bool:
    text = text or ""
    return all(part in text for part in ("subject_definitions:", "summary:", "retention_analysis:",
                                         "detailed_description:", "<Video 1>", "<Picture 1>", "[video editing]"))


# ------------------------------------------------------------------ ffmpeg


def _run(command: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(command, capture_output=True, text=True)


def probe(path: str) -> dict:
    """{seconds, width, height, has_audio} of a video file."""
    out = _run(["ffprobe", "-v", "error", "-show_entries", "stream=codec_type,width,height:format=duration",
                "-of", "json", path])
    if out.returncode != 0:
        raise RequestError(f"Could not read the video: {out.stderr.strip()[-300:]}")
    data = json.loads(out.stdout or "{}")
    streams = data.get("streams") or []
    video = next((s for s in streams if s.get("codec_type") == "video"), None)
    if video is None:
        raise RequestError("That file has no video stream.")
    return {"seconds": float((data.get("format") or {}).get("duration") or 0.0),
            "width": int(video.get("width") or 0), "height": int(video.get("height") or 0),
            "has_audio": any(s.get("codec_type") == "audio" for s in streams)}


def cut_piece(source: str, start: int, frames: int, out: str) -> None:
    """Frames [start, start+frames) of the source at 24 fps, silent (the original sound goes back on at the end)."""
    result = _run(["ffmpeg", "-nostdin", "-y", "-v", "error", "-i", source, "-vf",
                   f"fps={FPS},trim=start_frame={start}:end_frame={start + frames},setpts=PTS-STARTPTS",
                   "-an", "-c:v", "libx264", "-preset", "fast", "-crf", "16", "-pix_fmt", "yuv420p", out])
    if result.returncode != 0:
        raise RuntimeError(f"ffmpeg could not cut the video: {result.stderr.strip()[-300:]}")


def stills(path: str, frames: int, count: int = FRAMES_SHOWN) -> list[bytes]:
    """``count`` JPEG stills spread across a piece, in order."""
    work = tempfile.mkdtemp(prefix="hawk_stills_")
    try:
        step = max(1, frames // count)
        _run(["ffmpeg", "-nostdin", "-y", "-v", "error", "-i", path, "-vf",
              f"select='not(mod(n\\,{step}))',scale='min(768,iw)':-2", "-vsync", "vfr", "-frames:v", str(count),
              "-q:v", "4", os.path.join(work, "s_%02d.jpg")])
        names = sorted(n for n in os.listdir(work) if n.endswith(".jpg"))
        return [open(os.path.join(work, n), "rb").read() for n in names]
    finally:
        shutil.rmtree(work, ignore_errors=True)


def join_pieces(files: list[str], skips: list[int], source: str, has_audio: bool, total: int, out: str) -> None:
    """The pieces end to end (dropping each piece's ``skip`` leading frames), with the source's own soundtrack."""
    inputs, chains = [], []
    for n, (path, skip) in enumerate(zip(files, skips)):
        inputs += ["-i", path]
        chains.append(f"[{n}:v]fps={FPS},trim=start_frame={skip},setpts=PTS-STARTPTS,format=yuv420p[v{n}]")
    graph = ";".join(chains) + ";" + "".join(f"[v{n}]" for n in range(len(files))) + \
        f"concat=n={len(files)}:v=1:a=0[v]"
    command = ["ffmpeg", "-nostdin", "-y", "-v", "error", *inputs]
    if has_audio:
        command += ["-i", source]
    command += ["-filter_complex", graph, "-map", "[v]"]
    if has_audio:
        command += ["-map", f"{len(files)}:a:0", "-c:a", "aac", "-b:a", "192k"]
    command += ["-c:v", "libx264", "-preset", "medium", "-crf", "17", "-pix_fmt", "yuv420p",
                "-t", f"{total / FPS:.3f}", "-movflags", "+faststart", out]
    result = _run(command)
    if result.returncode != 0:
        raise RuntimeError(f"ffmpeg could not join the pieces: {result.stderr.strip()[-400:]}")


# ------------------------------------------------------------------ the job


class ReplaceManager:
    """Runs replacement jobs (kind "replace" in the jobs table) as tasks in this process; resumes them after a restart."""

    def __init__(self, service, characters=None):
        self.service = service
        self.characters = characters
        self._tasks: dict[str, asyncio.Task] = {}
        service.replace_manager = self  # cancel() reaches the task through the service

    # ---- starting

    def _pictures(self, character: str | None, picture_asset_ids: list[str] | None) -> tuple[list[str], str, str]:
        """(picture ids, name, description) for whoever goes into the video."""
        name, description, ids = "", "", list(picture_asset_ids or [])
        if character:
            if self.characters is None:
                raise RequestError("The character library isn't available on this server.")
            found = self.characters.find(character)
            name = found.get("name") or ""
            description = " ".join(filter(None, [found.get("facts") or "", found.get("notes") or ""]))
            if not ids:
                ids = list(found.get("identity_asset_ids") or [])
        ids = list(dict.fromkeys(i for i in ids if i))[:MAX_PICTURES]
        if not ids:
            raise RequestError("Give the character who goes into the video: a library character with identity pictures, "
                               "or picture_asset_ids.")
        for asset_id in ids:
            asset = self.service.store.get_asset(asset_id)
            if asset is None:
                raise RequestError(f"Unknown picture {asset_id!r}.")
            if asset.get("kind") != "image":
                raise RequestError(f"{asset.get('filename') or asset_id} is not a picture.")
            problem = origin_problem(self.service.store, asset_id)
            if problem:
                raise RequestError(
                    f"Only a character whose face was generated here can be put into a video, and {problem}. "
                    "Use pictures made with this server's image engines (Studio's image tab, a chat, Story or a "
                    "storyboard), not an uploaded photo or anything edited from one.")
        return ids, name, description

    async def _render_as_asset(self, job_id: str) -> str:
        """A finished render's video as a Library asset, so it can be the source of a replacement."""
        from .manhwa import rendered_file

        render = self.service.store.get_job(job_id)
        if render is None or render.get("kind") != "render" or render.get("status") != "done":
            raise RequestError(f"Render {job_id!r} has no finished video.")
        work = tempfile.mkdtemp(prefix="hawk_replace_src_")
        try:
            path = await rendered_file(self.service, job_id, os.path.join(work, "render.mp4"))
            with open(path, "rb") as handle:
                asset = await self.service.add_asset(
                    f"render_{job_id[:8]}.mp4", handle, "video/mp4", os.path.getsize(path), collection="Renders",
                    tags=["render"], local_path=path,
                    source={"type": "generated", "engine": "h3", "generator": "render", "job": job_id, "references": []})
            return asset["id"]
        finally:
            shutil.rmtree(work, ignore_errors=True)

    async def start(self, *, video_asset_id: str | None = None, who: str, character: str | None = None,
                    source_job_id: str | None = None,
                    picture_asset_ids: list[str] | None = None, direction: str = "",
                    settings: RenderSettings | None = None, by: str | None = None) -> dict:
        if not shutil.which("ffmpeg") or not shutil.which("ffprobe"):
            raise Unavailable("ffmpeg is not installed on the server; run the notebook's ffmpeg cell.")
        who = (who or "").strip()
        if not who:
            raise RequestError("Say who in the video is replaced, e.g. 'the woman in the red dress'.")
        pictures, name, description = self._pictures(character, picture_asset_ids)  # refused before anything is copied
        if not video_asset_id and source_job_id:
            video_asset_id = await self._render_as_asset(source_job_id)
        if not video_asset_id:
            raise RequestError("Give the video to change: video_asset_id from the Library, or source_job_id of a render.")
        video = self.service.store.get_asset(video_asset_id)
        if video is None:
            raise RequestError(f"Unknown video {video_asset_id!r}. Upload it to the Library first.")
        if video.get("kind") != "video":
            raise RequestError(f"{video.get('filename') or video_asset_id} is not a video.")
        # Uploads live in ComfyUI's input folder, which a Colab restart empties while the library still lists them:
        # say so here, not as a job that fails a moment later.
        lost = [a.get("filename") or a["id"] for a in [video, *[self.service.store.get_asset(p) for p in pictures]]
                if a is not None and not await self.service.ensure_asset_on_disk(a)]
        if lost:
            raise RequestError(self.service._lost_files_message(lost))
        job = self.service._new_job(
            "replace",
            request={"video_asset_id": video_asset_id, "who": who[:300], "character": character or "",
                     "picture_asset_ids": pictures, "direction": (direction or "")[:2000],
                     "settings": (settings or RenderSettings()).model_dump()},
            character_name=name, character_description=description[:1200], pieces=[], output_asset_id=None,
            by=by,
        )
        job["status"] = "rendering"
        job["started_at"] = time.time()
        self.service.store.save_job(job)
        self._launch(job["id"])
        return self.service.store.get_job(job["id"]) or job

    def _launch(self, job_id: str) -> None:
        task = asyncio.create_task(self._run(job_id))
        self._tasks[job_id] = task
        task.add_done_callback(lambda finished: self._tasks.pop(job_id, None) if self._tasks.get(job_id) is finished else None)

    async def resume(self) -> None:
        """Pick up replacement jobs a restart interrupted: cut pieces and submitted renders are reused."""
        for job in self.service.store.list_jobs(limit=500, statuses=ACTIVE):
            if job["kind"] == "replace" and job["id"] not in self._tasks:
                self._launch(job["id"])

    async def stop(self) -> None:
        for task in list(self._tasks.values()):
            task.cancel()
        if self._tasks:
            await asyncio.gather(*self._tasks.values(), return_exceptions=True)

    def cancel(self, job_id: str) -> None:
        task = self._tasks.get(job_id)
        if task is not None and not task.done():
            task.cancel()

    # ---- running

    def _job(self, job_id: str) -> dict:
        job = self.service.store.get_job(job_id)
        if job is None:
            raise NotFound(f"No job {job_id!r}.")
        return job

    def _save(self, job_id: str, **fields) -> dict:
        job = self._job(job_id)
        job.update(fields)
        self.service.store.save_job(job)
        return job

    async def _run(self, job_id: str) -> None:
        work = tempfile.mkdtemp(prefix="hawk_replace_")
        try:
            job = self._job(job_id)
            if job["status"] not in ACTIVE:
                return
            request = job["request"]
            video = self.service.store.get_asset(request["video_asset_id"])
            if video is None:
                raise RequestError("The source video is no longer in the Library.")
            source = os.path.join(work, "source" + (os.path.splitext(video.get("filename") or "")[1] or ".mp4"))
            with open(source, "wb") as handle:
                handle.write(await self.service.asset_bytes(video))
            info = await asyncio.to_thread(probe, source)
            if info["seconds"] > MAX_SECONDS + 0.5:
                raise RequestError(f"The video is {info['seconds']:.0f} s; person replacement takes up to "
                                   f"{MAX_SECONDS:.0f} s. Trim it first.")
            total = max(5, round(info["seconds"] * FPS))
            if not job.get("pieces"):
                cuts = cut_pieces(total)
                job = self._save(job_id, pieces=cuts, total_frames=total, source_info=info, segments_total=len(cuts),
                                 segments_done=0)
            settings = RenderSettings(**request["settings"])
            if "aspect_ratio" not in settings.model_fields_set and info["width"] and info["height"]:
                settings = settings.model_copy(update={"aspect_ratio": nearest_aspect(info["width"], info["height"])})
            settings = settings.model_copy(update={"continuity": "off", "music_asset_id": None,
                                                   "use_default_loras": settings.use_default_loras})

            for number, piece in enumerate(self._job(job_id)["pieces"], 1):
                if piece.get("job_id"):
                    continue
                self._save(job_id, current_segment=number, note=f"Preparing piece {number} of {len(job['pieces'])}")
                path = os.path.join(work, f"piece_{number:02d}.mp4")
                await asyncio.to_thread(cut_piece, source, piece["start"], piece["frames"], path)
                with open(path, "rb") as handle:
                    asset = await self.service.add_asset(
                        f"replace_{job_id[:8]}_piece{number:02d}.mp4", handle, "video/mp4", os.path.getsize(path),
                        collection="Replace pieces", tags=["replace-piece"], local_path=path, dedupe=False,
                        source={"type": "generated", "engine": "ffmpeg", "generator": "replace piece",
                                "references": [video["id"]], "job": job_id})
                prompt = await self._prompt(job, path, piece["frames"], len(request["picture_asset_ids"]))
                script = {"style": "", "segments": [{
                    "title": f"Piece {number}", "duration": piece["frames"] / FPS, "continuity": "off",
                    "pictures": list(range(1, len(request["picture_asset_ids"]) + 1)), "videos": [1], "prompt": prompt}]}
                references = [ReferenceIn(asset_id=asset["id"], role="video", label=f"source video, piece {number}")]
                references += [ReferenceIn(asset_id=p, role="picture", label=f"identity of {job.get('character_name') or 'the character'}")
                               for p in request["picture_asset_ids"]]
                render = await self.service.create_video(VideoRequest(references=references, script=script,
                                                                      settings=settings))
                child = self.service.store.get_job(render["id"])
                if child is not None:  # shown inside this job in Studio rather than as a video of its own
                    child["parent_job_id"] = job_id
                    self.service.store.save_job(child)
                job = self._job(job_id)
                job["pieces"][number - 1].update(asset_id=asset["id"], job_id=render["id"], prompt=prompt)
                self.service.store.save_job(job)

            files, skips = [], []
            for number, piece in enumerate(self._job(job_id)["pieces"], 1):
                self._save(job_id, current_segment=number, note=f"Rendering piece {number} of {len(job['pieces'])}")
                done = await self._wait(piece["job_id"])
                if done.get("status") != "done":
                    raise RequestError(f"Piece {number} ({piece['job_id'][:8]}) did not finish: "
                                       f"{done.get('error') or done.get('status')}. Retry this job: finished pieces "
                                       "are kept.")
                self._save(job_id, segments_done=number)
                from .manhwa import rendered_file
                files.append(await rendered_file(self.service, piece["job_id"], os.path.join(work, f"out_{number:02d}.mp4")))
                skips.append(piece.get("skip", 0))

            self._save(job_id, note="Joining the pieces and laying the original sound back on")
            out = os.path.join(work, "replaced.mp4")
            job = self._job(job_id)
            await asyncio.to_thread(join_pieces, files, skips, source, info["has_audio"],
                                    sum(p["frames"] - p.get("skip", 0) for p in job["pieces"]), out)
            base = os.path.splitext(video.get("filename") or "video")[0][:40]
            who = (job.get("character_name") or "character").replace(" ", "-")
            with open(out, "rb") as handle:
                asset = await self.service.add_asset(
                    f"{base}_replaced-with-{who}.mp4", handle, "video/mp4", os.path.getsize(out),
                    collection="Replaced", tags=["replaced", "generated"], local_path=out, dedupe=False,
                    source={"type": "generated", "engine": "ffmpeg", "generator": "person replacement",
                            "references": [video["id"], *request["picture_asset_ids"]], "job": job_id,
                            "jobs": [p["job_id"] for p in job["pieces"]]})
            from .manhwa import film_to_drive
            drive = await film_to_drive(self.service, out, asset["filename"])
            self._save(job_id, status="done", output_asset_id=asset["id"], drive_path=drive, note="",
                       current_segment=None, finished_at=time.time())
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            log.warning("replace %s failed: %s", job_id, exc)
            job = self.service.store.get_job(job_id)
            if job is not None and job["status"] in ACTIVE:
                job.update(status="failed", error=str(exc), resumable=True, note="")
                self.service.store.save_job(job)
        finally:
            shutil.rmtree(work, ignore_errors=True)

    async def _wait(self, job_id: str) -> dict:
        deadline = time.monotonic() + RENDER_WAIT_SECONDS
        while time.monotonic() < deadline:
            job = self.service.store.get_job(job_id) or {}
            if not job or job.get("status") in ("done", "failed", "cancelled"):
                return job
            await asyncio.sleep(POLL_SECONDS)
        return {"status": "timed out"}

    async def _prompt(self, job: dict, piece: str, frames: int, pictures: int) -> str:
        """This piece's six-section prompt from a vision model that sees the character and the piece; the template when
        none answers or its reply is unusable."""
        request = job["request"]
        fallback = template_prompt(request["who"], job.get("character_name") or "",
                                   job.get("character_description") or "", pictures, request.get("direction") or "")
        try:
            from . import models_llm
            from .atlas import AtlasError

            chain = models_llm.resolve_many("vision", None, await self.service.model_catalogue(), vision=True)
            if not chain:
                return fallback
            parts: list[dict] = []
            for asset_id in request["picture_asset_ids"]:
                data, kind = await self.service.asset_file(asset_id, 640)
                parts.append({"type": "image_url", "image_url": {"url": f"data:{kind};base64," + base64.b64encode(data).decode()}})
            shots = await asyncio.to_thread(stills, piece, frames)
            for data in shots:
                parts.append({"type": "image_url", "image_url": {"url": "data:image/jpeg;base64," + base64.b64encode(data).decode()}})
            text = (f"Direction: replace {request['who']} with <Subject 1>."
                    + (f" {request['direction']}" if request.get("direction") else "")
                    + f"\nCharacter: {job.get('character_name') or 'unnamed'}"
                    + (f" -- {job['character_description']}" if job.get("character_description") else "")
                    + f"\nImages: the first {pictures} are the character's identity pictures <Picture 1>"
                    + (f" to <Picture {pictures}>" if pictures > 1 else "")
                    + f"; the remaining {len(shots)} are stills from <Video 1> ({frames / FPS:.1f} s), in playback order.")
            messages = [{"role": "system", "content": SYSTEM_PROMPT},
                        {"role": "user", "content": [{"type": "text", "text": text}, *parts]}]
            for model in chain:
                try:
                    reply, _ = await self.service.atlas.chat(model, messages, json_mode=False, max_tokens=3000,
                                                             temperature=0.3, max_retries=1, purpose="replace prompt")
                except AtlasError as exc:
                    log.info("replace prompt: %s could not answer (%s)", model, exc)
                    continue
                reply = (reply or "").strip().strip("`").strip()
                if usable_prompt(reply) and not any(f"<Picture {n}>" in reply for n in range(pictures + 1, 10)):
                    return reply
        except Exception as exc:  # the prompt writer is an improvement, never a reason the job can't run
            log.warning("replace prompt fell back to the template: %s", exc)
        return fallback


def job_view_fields(service, job: dict) -> dict:
    """What a replacement job adds to the jobs view: its pieces and, once done, the finished video."""
    from .auth import sign_path

    view = {"pieces": [{k: p.get(k) for k in ("start", "frames", "skip", "job_id", "asset_id")}
                       for p in job.get("pieces") or []],
            "note": job.get("note") or "", "output_asset_id": job.get("output_asset_id"),
            "video_url": None}
    asset = service.store.get_asset(job["output_asset_id"]) if job.get("output_asset_id") else None
    if asset is not None:
        base, token, ttl = service.settings.public_base_url, service.settings.token, service.settings.link_ttl_seconds
        view["video_url"] = base + sign_path(token, f"/v1/assets/{asset['id']}/file", ttl)
        view["download_url"] = view["video_url"] + "&download=1"
        view["thumb_url"] = base + sign_path(token, f"/v1/assets/{asset['id']}/file", ttl) + "&w=640"
    return view
